import { test, expect } from '@playwright/test'
import { fillEmailCode } from './emailCode'

test('账户注册、登录、知识库创建与退出', async ({ page }) => {
  const email = `e2e-${Date.now()}@example.org`
  await page.goto('/')
  await expect(page.getByRole('heading', { name: '欢迎回来' })).toBeVisible()
  await page.screenshot({ path: 'test-results/m0-login.png', fullPage: true })
  await page.getByRole('button', { name: '免费注册' }).click()
  await page.getByLabel('邮箱地址').fill(email)
  await fillEmailCode(page, email)
  await expect(page.getByRole('button', { name: /秒后重发/ })).toBeDisabled()
  await page.getByLabel('密码', { exact: true }).fill('Trial123')
  await page.getByRole('button', { name: '创建账户', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('注册成功，邮箱已验证')
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await expect(page.getByRole('heading', { name: '我的知识库' })).toBeVisible()
  await expect(page.getByText('请验证邮箱，以便后续上传论文和使用问答服务。')).toHaveCount(0)
  await page.getByRole('button', { name: '新建知识库' }).click()
  await page.getByLabel('名称', { exact: true }).fill('浏览器测试知识库')
  await page.getByLabel('描述（可选）').fill('一次真实 API 交互')
  await page.getByRole('button', { name: '创建', exact: true }).click()
  await expect(page.getByRole('heading', { name: '浏览器测试知识库' })).toBeVisible()
  await page.screenshot({ path: 'test-results/m0-workspace.png', fullPage: true })
  // 图标和卡片空白处都能进入，键盘仍可操作标题按钮。
  const card = page.locator('.collection-card')
  const folderIcon = await card.locator('.folder-icon').boundingBox()
  expect(folderIcon).not.toBeNull()
  await page.mouse.click(folderIcon!.x + folderIcon!.width / 2, folderIcon!.y + folderIcon!.height / 2)
  await expect(page.getByRole('heading', { name: '上传论文' })).toBeVisible()
  await page.getByRole('button', { name: '返回知识库', exact: true }).click()
  await card.click({ position: { x: 8, y: 8 } })
  await expect(page.getByRole('heading', { name: '上传论文' })).toBeVisible()
  await page.getByRole('button', { name: '返回知识库', exact: true }).click()
  await page.getByRole('button', { name: '浏览器测试知识库', exact: true }).focus()
  await page.keyboard.press('Enter')
  await expect(page.getByRole('heading', { name: '上传论文' })).toBeVisible()
  await page.getByRole('button', { name: '返回知识库', exact: true }).click()
  page.once('dialog', dialog => dialog.dismiss())
  await page.getByRole('button', { name: '删除 浏览器测试知识库' }).click()
  await expect(card).toBeVisible()
  await expect(page.getByRole('heading', { name: '上传论文' })).toHaveCount(0)
  page.once('dialog', dialog => dialog.accept())
  await page.getByRole('button', { name: '删除 浏览器测试知识库' }).click()
  await expect(page.getByRole('heading', { name: '从一个研究方向开始' })).toBeVisible()

  // 删除未选中的会话不切换当前会话，删除最后一个后可以继续新建。
  await page.getByRole('button', { name: '问答工作台', exact: true }).click()
  await page.getByRole('button', { name: '新建会话', exact: true }).click()
  await expect(page.locator('.conversation-item')).toHaveCount(1)
  await page.getByRole('button', { name: '新建会话', exact: true }).click()
  await expect(page.locator('.conversation-item')).toHaveCount(2)
  const activeTitle = page.locator('.conversation-item.active .conversation-select')
  await expect(activeTitle).toHaveCount(1)
  page.once('dialog', dialog => dialog.dismiss())
  await page.locator('.conversation-item:not(.active) .conversation-delete').click()
  await expect(page.locator('.conversation-item')).toHaveCount(2)
  page.once('dialog', dialog => dialog.accept())
  await page.locator('.conversation-item:not(.active) .conversation-delete').click()
  await expect(page.locator('.conversation-item')).toHaveCount(1)
  await expect(activeTitle).toHaveCount(1)
  await page.getByRole('button', { name: '新建会话', exact: true }).click()
  await expect(page.locator('.conversation-item')).toHaveCount(2)
  page.once('dialog', dialog => dialog.accept())
  await page.locator('.conversation-item.active .conversation-delete').click()
  await expect(page.locator('.conversation-item')).toHaveCount(1)
  await expect(activeTitle).toHaveCount(1)
  page.once('dialog', dialog => dialog.accept())
  await page.getByRole('button', { name: '删除会话 新会话', exact: true }).click()
  await expect(page.locator('.conversation-item')).toHaveCount(0)
  await expect(page.getByText('输入问题自动开启你的第一个研究问答会话。')).toBeVisible()
  await page.reload()
  await page.getByRole('button', { name: '问答工作台', exact: true }).click()
  await expect(page.locator('.conversation-item')).toHaveCount(0)
  await page.getByRole('button', { name: '新建会话', exact: true }).click()
  await expect(page.locator('.conversation-item')).toHaveCount(1)
  await page.getByRole('button', { name: '退出登录' }).click()
  await expect(page.getByRole('heading', { name: '欢迎回来' })).toBeVisible()
})

