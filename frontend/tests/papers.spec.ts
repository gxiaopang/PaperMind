import { test, expect } from '@playwright/test'

test('已验证账户上传论文、查看进度、编辑与删除', async ({ page }) => {
  await page.goto('/')
  await page.getByLabel('邮箱地址').fill('m2-browser@example.org')
  await page.getByLabel('密码', { exact: true }).fill('Browser test password 123!')
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await page.getByRole('button', { name: '新建知识库' }).click()
  await page.getByLabel('名称', { exact: true }).fill('论文入库测试')
  await page.getByRole('button', { name: '创建', exact: true }).click()
  await page.getByRole('button', { name: '论文入库测试', exact: true }).click()
  const upload = page.getByRole('button', { name: '上传并入库' })
  await expect(upload).toBeDisabled()
  await page.getByLabel('PDF 文件', { exact: true }).setInputFiles(process.env.PAPERMIND_E2E_PDF!)
  await expect(upload).toBeDisabled()
  await page.getByRole('checkbox').check()
  await upload.click()
  await expect(page.getByText('等待入库', { exact: true })).toBeVisible()
  await expect(page.getByRole('link', { name: '查看 PDF' })).toHaveAttribute('href', /pdf$/)
  await expect(page.getByRole('button', { name: '重新分块', exact: true })).toBeDisabled()
  await page.screenshot({ path: 'test-results/m2-papers.png', fullPage: true })
  await page.getByRole('button', { name: '编辑信息' }).click()
  await page.getByLabel('论文标题').fill('浏览器测试论文')
  await page.getByLabel('作者（用中文分号分隔）').fill('作者甲；作者乙')
  await page.getByRole('button', { name: '保存', exact: true }).click()
  await expect(page.getByRole('heading', { name: '浏览器测试论文' })).toBeVisible()
  page.once('dialog', dialog => dialog.accept())
  await page.getByRole('button', { name: '删除论文', exact: true }).click()
  await expect(page.getByText('还没有论文，上传第一篇 PDF 开始积累。')).toBeVisible()
  await page.getByRole('button', { name: '返回知识库' }).click()
  await expect(page.getByRole('heading', { name: '我的知识库' })).toBeVisible()
})
